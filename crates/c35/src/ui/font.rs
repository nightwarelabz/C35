//! The UI font: a 5x7 dot-matrix defined as data, authored here.
//! No font file, no image asset, no borrowed table — every row
//! below was written for this engine. Bit 4 of each row byte is
//! the leftmost column; bit 0 the rightmost. Printable ASCII
//! 32..=126, in order; anything outside that range renders as
//! a space, never as a hole in the layout.
//!
//! The 5x7 cell is the PS1.5 read: chunky enough to survive
//! the 854x480 internal frame and the palette grade, small
//! enough for a dialogue line to hold a sentence. Glyphs are
//! drawn as solid quads per run of set pixels — no texture,
//! no atlas tile, so text costs runs, not pixels.

