/// Glyph for a character: printable ASCII maps into the table,
/// everything else is a space — text never breaks on input.
pub fn glyph_for(c: char) -> &'static Glyph {
    let code = c as usize;
    if (32..=126).contains(&code) {
        &FONT[code - 32]
    } else {
        &FONT[0]
    }
}

/// Set pixels in a glyph, as (column, row) pairs, column 0 left.
pub fn glyph_pixels(g: &Glyph) -> impl Iterator<Item = (u8, u8)> + '_ {
    (0..7).flat_map(move |row| {
        (0..5).filter_map(move |col| {
            if g[row] & (1 << (4 - col)) != 0 {
                Some((col as u8, row as u8))
            } else {
                None
            }
        })
    })
}
